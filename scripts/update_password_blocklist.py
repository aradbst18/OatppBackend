#!/usr/bin/env python3
"""Keep policy-relevant passwords from the SecLists top-million UTF-8 list."""

import hashlib
import json
from pathlib import Path
import sys


def render(source):
    passwords = sorted({
        password
        for password in (line.removesuffix("\r") for line in source.decode("utf-8").split("\n"))
        if 15 <= len(password) <= 128
        and not any(ord(c) < 32 or 127 <= ord(c) <= 159 for c in password)
    })
    if not passwords:
        raise ValueError("Source contains no passwords within the 15-128 character policy")
    checksum = hashlib.sha256(source).hexdigest()
    return (
        "// Generated by scripts/update_password_blocklist.py; do not edit individual entries.\n"
        "// Source: SecLists/Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt\n"
        f"// Source SHA-256: {checksum}; see LICENSE in this directory.\n"
        f"// {len(passwords)} entries: 15-128 Unicode code points, excluding control characters.\n"
        + "".join(f"    {json.dumps(p, ensure_ascii=False)},\n" for p in passwords)
    )


if __name__ == "__main__":
    assert render(b"beta password phrase\nalpha password phrase\nbeta password phrase\n").endswith(
        '    "alpha password phrase",\n    "beta password phrase",\n'
    )
    assert render(b'a long quote"\\password\n').endswith('    "a long quote\\\"\\\\password",\n')
    sample = "\n".join(["x" * 14, "x" * 15, "y" * 128, "y" * 129, "a password\0with NUL",
                        "a password\twith tab", "a password\x7fwith DEL", "a password\x85with C1"])
    assert render(sample.encode()).splitlines()[4:] == [f'    "{"x" * 15}",', f'    "{"y" * 128}",']
    assert render(("🌊" * 14 + "\n" + "🌊" * 15).encode()).splitlines()[4:] == [f'    "{"🌊" * 15}",']
    assert render(b" spaces stay here \n").endswith('    " spaces stay here ",\n')
    assert render(b" spaces stay here \r\n").endswith('    " spaces stay here ",\n')
    source_path = Path(sys.argv[1])
    output = Path(__file__).resolve().parents[1] / "src/validation/passwords/CommonPasswords.inc"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(source_path.read_bytes()), encoding="utf-8")
